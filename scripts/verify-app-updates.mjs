import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const updates = read('app/src/main/java/com/sunswift/ula/UlaAppUpdates.kt');
const main = read('app/src/main/java/com/sunswift/ula/MainActivity.kt');
const web = read('app/src/main/java/com/sunswift/ula/UlaWebScreen.kt');
assert.match(read('app/build.gradle'), /com.google.android.play:app-update:2.1.0/);
assert.match(updates, /info.availableVersionCode\(\) > installedCode/);
assert.match(updates, /info.availableVersionCode\(\) <= installedCode/);
assert.match(main, /AppUpdateType.FLEXIBLE/);
assert.ok(!main.includes('AppUpdateType.IMMEDIATE'));
assert.ok(!updates.includes('setAllowAssetPackDeletion(true)'));
assert.match(updates, /Restart and update/);
assert.match(updates, /Save any unsaved form changes/);
assert.match(updates, /stage != UpdateStage.READY/);
assert.match(updates, /manager.unregisterListener/);
assert.match(updates, /testBuild/);
assert.match(updates, /cannot|Cannot check Google Play/);
assert.ok(main.includes('AppUpdatesLink()') && web.includes('AppUpdatesLink()'));
assert.match(main.slice(main.indexOf('private fun SessionLoadingScreen()'), main.indexOf('private fun AppMark()')), /AppUpdatesLink\(\)/, 'Updates must be accessible even if the backend session check is slow');
assert.match(read('app/src/debug/res/values/strings.xml'), /SunSwift ULA TEST/);
assert.match(read('app/src/main/res/values/strings.xml'), /SunSwift ULA<\/string>/);
assert.ok(!read('app/src/main/AndroidManifest.xml').includes('REQUEST_INSTALL_PACKAGES'));
assert.ok(!updates.includes('sessionToken') && !updates.includes('ownerMobile'));
console.log('PASS: Play-controlled newer-build checks; explicit flexible consent/restart; safe errors, isolated TEST label, unchanged install permissions and no ULA credentials in store links.');
